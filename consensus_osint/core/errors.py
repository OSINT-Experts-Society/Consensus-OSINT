TEMPORARY_KINDS = {"Rate limited", "Request timeout", "Server", "Connecting failure"}


def detect_error_page(
    text: str,
    status: int,
    fail_flags: dict | None = None,
    ignore_403: bool = False,
) -> CheckError | None:
    """Classify a response; returns None when it looks like a normal page.

    Order: site-specific failure markers, generic bot-protection wording, then
    HTTP status (403 unless ignored, 401, 429, 5xx). HTTP 999 is access denied;
    a refusal does not establish whether the requested account exists.
    """
    if fail_flags and text:
        for flag, msg in fail_flags.items():
            if flag and flag in text:
                return CheckError("Site-specific", str(msg))
    if text:
        for marker, err in COMMON_MARKERS:
            if marker in text:
                return err
    if status == 403 and not ignore_403:
        return CheckError("Access denied", "HTTP 403")
    if status == 401:
        return CheckError("Login required", "HTTP 401")
    if status == 429:
        return CheckError("Rate limited", "HTTP 429")
    if status == 999:
        return CheckError("Access denied", "HTTP 999")
    if status >= 500:
        return CheckError("Server", f"HTTP {status}")
    return None


