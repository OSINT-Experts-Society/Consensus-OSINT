"""Bot-protection / error-page detection.

A page that is a Cloudflare challenge, a captcha wall or a rate-limit notice
must never be read as "username is free" (a silent false negative) nor as
"profile exists" (a false positive).  The marker list combines Maigret's
``errors.py`` (MIT, (c) Soxoj) and Sherlock's WAF hit list (MIT, Sherlock
Project), plus a few additions. Complete original notices and the scope of
these adaptations are retained in THIRD_PARTY_NOTICES.txt and licenses/.
"""
from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class CheckError:
    kind: str       # Captcha, Bot protection, Access denied, Rate limited, Login required, Censorship, Server ...
    detail: str = ""

    def __str__(self) -> str:
        return f"{self.kind}: {self.detail}" if self.detail else self.kind


# substring -> error (order matters: first hit wins)
